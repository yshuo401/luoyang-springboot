CREATE TABLE banner (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    title VARCHAR(128) NOT NULL,
    subtitle VARCHAR(255) NULL,
    image_file_id BIGINT UNSIGNED NOT NULL,
    link_type TINYINT UNSIGNED NOT NULL DEFAULT 0,
    target_id BIGINT UNSIGNED NULL,
    target_path VARCHAR(255) NULL,
    position VARCHAR(32) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    status TINYINT UNSIGNED NOT NULL DEFAULT 1,
    start_at DATETIME(3) NULL,
    end_at DATETIME(3) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    created_by BIGINT UNSIGNED NULL,
    updated_by BIGINT UNSIGNED NULL,
    version INT UNSIGNED NOT NULL DEFAULT 0,
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_banner_position_status (position, status, is_deleted, sort_order),
    KEY idx_banner_time (status, start_at, end_at),
    KEY idx_banner_target (link_type, target_id),
    KEY idx_banner_image_file (image_file_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
