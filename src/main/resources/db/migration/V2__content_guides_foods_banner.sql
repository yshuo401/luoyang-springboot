CREATE TABLE travel_guide (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    title VARCHAR(200) NOT NULL,
    slug VARCHAR(200) NULL,
    summary VARCHAR(1000) NULL,
    cover_file_id BIGINT UNSIGNED NULL,
    author_name VARCHAR(64) NULL,
    content_html MEDIUMTEXT NULL,
    travel_days SMALLINT UNSIGNED NULL,
    difficulty TINYINT UNSIGNED NULL,
    suitable_season VARCHAR(64) NULL,
    heat_score INT UNSIGNED NOT NULL DEFAULT 0,
    recommendation_weight INT UNSIGNED NOT NULL DEFAULT 0,
    status TINYINT UNSIGNED NOT NULL DEFAULT 0,
    published_at DATETIME(3) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    created_by BIGINT UNSIGNED NULL,
    updated_by BIGINT UNSIGNED NULL,
    version INT UNSIGNED NOT NULL DEFAULT 0,
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_travel_guide_slug (slug),
    KEY idx_travel_guide_status_publish (status, is_deleted, published_at),
    KEY idx_travel_guide_heat (status, is_deleted, heat_score),
    KEY idx_travel_guide_title (title),
    KEY idx_travel_guide_cover_file (cover_file_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE guide_day (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    guide_id BIGINT UNSIGNED NOT NULL,
    day_no SMALLINT UNSIGNED NOT NULL,
    title VARCHAR(128) NOT NULL,
    summary VARCHAR(1000) NULL,
    traffic_tip TEXT NULL,
    accommodation_tip TEXT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    is_deleted TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_guide_day_no (guide_id, day_no, is_deleted),
    KEY idx_guide_day_guide (guide_id, is_deleted, day_no)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE guide_day_spot (
